const byId = new Map(glossary.map((t) => [t.id, t]));
export const termById = (id: string) => byId.get(id);

/** 본문 자동 연결에 쓰는 표기 → id 표. 긴 표기가 먼저 오도록 정렬해 둔다. */
export const autoPhrases: { phrase: string; id: string }[] = glossary
  .filter((t) => !t.noauto)
  .flatMap((t) => [t.term, ...(t.aliases ?? [])].map((phrase) => ({ phrase, id: t.id })))
  .filter(({ phrase }) => phrase.length >= 2)
  .sort((a, b) => b.phrase.length - a.phrase.length);

